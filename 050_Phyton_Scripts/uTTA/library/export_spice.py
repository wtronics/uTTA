from thermal_network.conversions import FosterNetwork, CauerNetwork


def create_ltspice_foster(network:FosterNetwork) -> list[str]:
    """ Generates an LTspice subcircuit netlist for a Foster thermal network.

        Args:
            network (FosterNetwork): The Foster network model to export.

        Returns:
            list[str]: Lines of the generated LTspice subcircuit netlist.

        Raises:
            ValueError: If the network order is 0.
        """
    if network.order == 0:
        raise ValueError("Foster Network seems to be empty")

    subckt_name = f"THERMAL_FOSTER_{network.order}ORDER"

    lines = [
        f"* LTspice Thermal Network Subcircuit (FOSTER)",
        f"* Generated by Thermal Network Fitting Tool\n",
        f".SUBCKT {subckt_name} T_in T_out\n"
    ]

    last_node = "T_in"
    for i, (r, c) in enumerate(zip(network.r, network.c), 1):
        next_node = f"N{i}" if i < network.order else "T_out"

        lines.append(f"R{i} {last_node} {next_node} {r:.6e}")
        lines.append(f"C{i} {last_node} {next_node} {c:.6e}\n")
        last_node = next_node

    lines.append(f".ENDS {subckt_name}\n")

    return lines

def create_ltspice_cauer(network:CauerNetwork) -> list[str]:
    """Generates an LTspice subcircuit netlist for a Cauer thermal network.

        Args:
            network (CauerNetwork): The Cauer network model to export.

        Returns:
            list[str]: Lines of the generated LTspice subcircuit netlist.

        Raises:
            ValueError: If the network order is 0.
        """
    if network.order == 0:
        raise ValueError("Cauer Network seems to be empty")

    subckt_name = f"THERMAL_CAUER_{network.order}ORDER"

    lines = [
        f"* LTspice Thermal Network Subcircuit (CAUER)",
        f"* Generated by Thermal Network Fitting Tool\n",
        f"* In case this thermal model reflects the whole thermal chain, connect T_out to T_amb\n",
        f".SUBCKT {subckt_name} T_in T_out T_amb\n"
    ]

    last_node = "T_in"
    for i, (r, c) in enumerate(zip(network.r, network.c), 1):
        next_node = f"N{i}" if i < network.order else "T_out"

        lines.append(f"C{i} {last_node} T_amb {c:.6e}")
        lines.append(f"R{i} {last_node} {next_node} {r:.6e}\n")
        
        last_node = next_node

    lines.append(f".ENDS {subckt_name}\n")

    return lines